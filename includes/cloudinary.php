<?php
// Cloudinary credentials stay on the server; no unsigned upload preset is needed.
function cloudinary_config(): array
{
    return require __DIR__ . '/../config/cloudinary.php';
}

function cloudinary_ready(): bool
{
    $c = cloudinary_config();
    return function_exists('curl_init')
        && preg_match('/^[a-zA-Z0-9_-]{1,64}$/D', $c['cloud_name']) === 1
        && ctype_digit($c['api_key']) && $c['api_secret'] !== ''
        && strlen($c['folder']) <= 64
        && preg_match('~^[a-zA-Z0-9_-]+(?:/[a-zA-Z0-9_-]+)*$~D', $c['folder']) === 1;
}

function cloudinary_signature(array $params, string $secret): string
{
    ksort($params, SORT_STRING);
    $parts = [];
    foreach ($params as $key => $value) $parts[] = $key . '=' . $value;
    return hash('sha256', implode('&', $parts) . $secret);
}

function cloudinary_request(string $action, array $params, ?CURLFile $file = null): array
{
    if (!in_array($action, ['upload', 'destroy'], true)) throw new InvalidArgumentException('Invalid image action.');
    if (!cloudinary_ready()) throw new RuntimeException('Dịch vụ lưu ảnh chưa được cấu hình. Vui lòng liên hệ quản trị viên.');
    $c = cloudinary_config();
    $params['timestamp'] = (string)time();
    $fields = $params + ['api_key' => $c['api_key'], 'signature' => cloudinary_signature($params, $c['api_secret'])];
    if ($file !== null) $fields['file'] = $file;

    $ch = curl_init('https://api.cloudinary.com/v1_1/' . $c['cloud_name'] . '/image/' . $action);
    if ($ch === false) throw new RuntimeException('Không thể kết nối dịch vụ lưu ảnh. Vui lòng thử lại.');
    curl_setopt_array($ch, [
        CURLOPT_POST => true,
        CURLOPT_POSTFIELDS => $fields,
        CURLOPT_RETURNTRANSFER => true,
        CURLOPT_CONNECTTIMEOUT => 10,
        CURLOPT_TIMEOUT => 45,
        CURLOPT_SSL_VERIFYPEER => true,
        CURLOPT_SSL_VERIFYHOST => 2,
        CURLOPT_PROTOCOLS => CURLPROTO_HTTPS,
        CURLOPT_FOLLOWLOCATION => false,
    ]);
    try {
        $raw = curl_exec($ch);
        $status = (int)curl_getinfo($ch, CURLINFO_RESPONSE_CODE);
        $data = is_string($raw) ? json_decode($raw, true, 32) : null;
        if ($raw === false || $status < 200 || $status >= 300 || !is_array($data) || isset($data['error'])) {
            // Do not log API bodies, signed fields or credentials.
            error_log('FishShop Cloudinary ' . $action . ' failed; HTTP ' . $status . ', cURL ' . curl_errno($ch) . '.');
            throw new RuntimeException('Không thể lưu ảnh lúc này. Vui lòng thử lại sau.');
        }
        return $data;
    } finally {
        curl_close($ch);
    }
}

function cloudinary_upload_image(string $tempPath, string $subDir, string $extension): string
{
    if (!cloudinary_ready()) throw new RuntimeException('Dịch vụ lưu ảnh chưa được cấu hình. Vui lòng liên hệ quản trị viên.');
    $c = cloudinary_config();
    $publicId = $c['folder'] . '/' . $subDir . '/' . bin2hex(random_bytes(12));
    $mime = ['jpg' => 'image/jpeg', 'png' => 'image/png', 'webp' => 'image/webp'][$extension];
    $data = cloudinary_request('upload', ['public_id' => $publicId, 'overwrite' => 'false'], new CURLFile($tempPath, $mime, 'image.' . $extension));

    $url = $data['secure_url'] ?? '';
    $format = is_string($data['format'] ?? null) ? $data['format'] : '';
    $versionValue = $data['version'] ?? null;
    $version = is_int($versionValue) || is_string($versionValue) ? (string)$versionValue : '';
    $expectedUrl = 'https://res.cloudinary.com/' . $c['cloud_name'] . '/image/upload/v' . $version . '/' . $publicId . '.' . $format;
    if (!is_string($url) || strlen($url) > 255 || $url !== $expectedUrl
        || !ctype_digit($version) || !in_array($format, ['jpg', 'jpeg', 'png', 'webp'], true)
        || ($data['public_id'] ?? null) !== $publicId || ($data['resource_type'] ?? null) !== 'image') {
        // A successful upload with an unusable response must not leave an unused asset.
        try { cloudinary_request('destroy', ['public_id' => $publicId, 'invalidate' => 'true']); }
        catch (Throwable $ignored) { error_log('FishShop Cloudinary upload cleanup failed.'); }
        throw new RuntimeException('Dịch vụ lưu ảnh trả về ảnh không hợp lệ. Vui lòng thử lại.');
    }
    return $url;
}

function cloudinary_public_id_from_url(string $url): ?string
{
    $c = cloudinary_config();
    // Only delete assets generated by this app, in the configured account and folders.
    $prefix = 'https://res.cloudinary.com/' . $c['cloud_name'] . '/image/upload/';
    if ($c['cloud_name'] === '' || $c['folder'] === '' || !str_starts_with($url, $prefix)) return null;
    $pattern = '~^v[0-9]+/(' . preg_quote($c['folder'], '~') . '/(?:products|avatars)/[a-f0-9]{24})\.(?:jpg|jpeg|png|webp)$~D';
    return preg_match($pattern, substr($url, strlen($prefix)), $matches) === 1 ? $matches[1] : null;
}

function cloudinary_delete_image(string $url): void
{
    $publicId = cloudinary_public_id_from_url($url);
    if ($publicId === null) return;
    $data = cloudinary_request('destroy', ['public_id' => $publicId, 'invalidate' => 'true']);
    if (!in_array($data['result'] ?? null, ['ok', 'not found'], true)) {
        throw new RuntimeException('Không xóa được ảnh cũ.');
    }
}
